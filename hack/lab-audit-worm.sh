#!/usr/bin/env bash
# REAL lab check of audit shipping into WORM storage (minikube, hack/lab-up.sh, Prometheus on :9090):
#   an S3 server with Object Lock (MinIO built from source, hack/lab/minio), the reference collector (tools/audit-collector: HTTPS
#   with a private CA, bearer token, one COMPLIANCE-locked object per event), the OPERATOR shipping its applier events over https
#   trusting that CA (chart auditURL + auditTokenSecret + auditCASecret), and the CLI shipping a chained trail the same way.
# Lab only: the MinIO data lives in an emptyDir and goes away with the namespace; the retention is real while it exists.
# Do not edit this file while it runs (bash reads scripts incrementally): copy it first.
set -u
CTX="${CTX:-kubecost-lab}"; PROM="${PROM:-http://localhost:9090}"
HERE="$(cd "$(dirname "$0")/.." && pwd)"; LAB="$HERE/.lab/audit-worm"; rm -rf "$LAB"; mkdir -p "$LAB"
K="kubectl --context $CTX"; H="helm --kube-context $CTX"; REL=applier; NS=kubecost-auto-hpa-system; AN=audit
[ "$CTX" = "kubecost-lab" ] || [ "${ALLOW_CTX:-}" = "1" ] || { echo "refusing context '$CTX'"; exit 2; }
curl -fs "$PROM/-/ready" >/dev/null || { echo "Prometheus not reachable"; exit 2; }
PASS=0; FAILN=0
ok()  { echo "PASS  $*"; PASS=$((PASS+1)); }
bad() { echo "FAIL  $*"; FAILN=$((FAILN+1)); }
check() { if eval "$2"; then ok "$1"; else bad "$1"; fi; }
(cd "$HERE/operator" && go build -o "$LAB/rightsize.exe" ./cmd/rightsize) || exit 2
(cd "$HERE/tools/audit-collector" && go build -o "$LAB/audit-collector.exe" .) || exit 2
RS="$LAB/rightsize.exe"; AC="$LAB/audit-collector.exe"
req() { $K -n lab get deploy "$1" -o jsonpath='{.spec.template.spec.containers[0].resources.requests.cpu}/{.spec.template.spec.containers[0].resources.requests.memory}'; }
phase() { $K -n lab get wrec "$1" -o jsonpath='{.status.phase}' 2>/dev/null; }
waitphase() { for _ in $(seq 1 "$3"); do [ "$(phase "$1")" = "$2" ] && return 0; sleep 5; done; return 1; }
plan() { for _ in $(seq 1 45); do
    "$RS" plan --context "$CTX" --prometheus-url "$PROM" --namespace lab --workload "$1" --container app --window 14m --step 15s \
      --min-window 8m --min-samples 40 ${3:-} > "$2" 2>"$2.err" &&
    [ "$(python -c "import json,sys; r=json.load(open(sys.argv[1])); print(not r['Abstained'] and r['Confidence'] in ('Medium','High'))" "$2")" = True ] && return 0
    sleep 20; done; return 1; }
wname() { python -c "import json,sys; r=json.load(open(sys.argv[1])); print(r['Workload'].lower() + '-' + r['ID'].lower())" "$1"; }
pf() { ($K -n "$1" port-forward "svc/$2" "$3" >/dev/null 2>&1 &); for _ in $(seq 1 20); do curl -sk -m 2 "https://localhost:${3%%:*}" >/dev/null 2>&1 || curl -s -m 2 "http://localhost:${3%%:*}" >/dev/null 2>&1; [ $? -ne 7 ] && return 0; sleep 1; done; }

echo "== 0. images, private CA, MinIO with Object Lock, the collector, the operator shipping to it over https"
docker build -q -t kubecost-auto-hpa-operator:lab --build-arg VERSION=lab "$HERE/operator" >/dev/null || exit 2
docker build -q -t kubecost-auto-hpa-engine:lab "$HERE/engine" >/dev/null || exit 2
docker build -q -t kubecost-audit-collector:lab "$HERE/tools/audit-collector" >/dev/null || exit 2
docker build -q -t kubecost-lab-minio:lab "$HERE/hack/lab/minio" >/dev/null || exit 2
minikube -p kubecost-lab image load kubecost-auto-hpa-operator:lab kubecost-auto-hpa-engine:lab kubecost-audit-collector:lab kubecost-lab-minio:lab || exit 2
# Git Bash rewrites a leading "/" in arguments into a Windows path; "//" escapes it there (and only there)
case "$(uname -s)" in MINGW*|MSYS*) SL=//;; *) SL=/;; esac
# a private CA and a server certificate for the collector's in-cluster name (and localhost, for the CLI through a port-forward)
openssl req -x509 -newkey ec -pkeyopt ec_paramgen_curve:P-256 -nodes -days 2 -subj "${SL}CN=kubecost-lab-audit-ca" \
  -keyout "$LAB/ca.key" -out "$LAB/ca.crt" >/dev/null 2>&1 || exit 2
printf 'subjectAltName=DNS:audit-collector.%s.svc,DNS:audit-collector.%s.svc.cluster.local,DNS:localhost,IP:127.0.0.1\n' $AN $AN > "$LAB/san.ext"
openssl req -newkey ec -pkeyopt ec_paramgen_curve:P-256 -nodes -subj "${SL}CN=audit-collector" -keyout "$LAB/tls.key" -out "$LAB/tls.csr" >/dev/null 2>&1
openssl x509 -req -in "$LAB/tls.csr" -CA "$LAB/ca.crt" -CAkey "$LAB/ca.key" -CAcreateserial -days 2 -extfile "$LAB/san.ext" -out "$LAB/tls.crt" >/dev/null 2>&1 || exit 2
TOKEN="tok-$(openssl rand -hex 16)"; printf '%s' "$TOKEN" > "$LAB/token"
S3K="lab$(openssl rand -hex 6)"; S3S="$(openssl rand -hex 20)"
$K create ns $AN >/dev/null 2>&1
$K -n $AN create secret generic s3 --from-literal=access="$S3K" --from-literal=secret="$S3S" --dry-run=client -o yaml | $K apply -f - >/dev/null
$K -n $AN create secret tls collector-tls --cert="$LAB/tls.crt" --key="$LAB/tls.key" --dry-run=client -o yaml | $K apply -f - >/dev/null
$K -n $AN create secret generic collector-token --from-file=token="$LAB/token" --dry-run=client -o yaml | $K apply -f - >/dev/null
$K create ns $NS >/dev/null 2>&1
$K -n $NS create secret generic audit-token --from-file=token="$LAB/token" --dry-run=client -o yaml | $K apply -f - >/dev/null
$K -n $NS create secret generic audit-ca --from-file=ca.crt="$LAB/ca.crt" --dry-run=client -o yaml | $K apply -f - >/dev/null
cat <<EOF | $K apply -f - >/dev/null
apiVersion: apps/v1
kind: Deployment
metadata: {name: minio, namespace: $AN}
spec:
  replicas: 1
  selector: {matchLabels: {app: minio}}
  template:
    metadata: {labels: {app: minio}}
    spec:
      containers:
      - name: minio
        image: kubecost-lab-minio:lab
        imagePullPolicy: Never
        args: [server, /data]
        env:
        - {name: MINIO_ROOT_USER, valueFrom: {secretKeyRef: {name: s3, key: access}}}
        - {name: MINIO_ROOT_PASSWORD, valueFrom: {secretKeyRef: {name: s3, key: secret}}}
        ports: [{containerPort: 9000}]
        readinessProbe: {httpGet: {path: /minio/health/ready, port: 9000}, periodSeconds: 3}
        volumeMounts: [{name: data, mountPath: /data}]
        resources: {requests: {cpu: 100m, memory: 256Mi}}
      volumes: [{name: data, emptyDir: {}}]
---
apiVersion: v1
kind: Service
metadata: {name: minio, namespace: $AN}
spec: {selector: {app: minio}, ports: [{port: 9000, targetPort: 9000}]}
---
apiVersion: apps/v1
kind: Deployment
metadata: {name: audit-collector, namespace: $AN}
spec:
  replicas: 1
  selector: {matchLabels: {app: audit-collector}}
  template:
    metadata: {labels: {app: audit-collector}}
    spec:
      containers:
      - name: collector
        image: kubecost-audit-collector:lab
        imagePullPolicy: Never
        args: [serve, --s3-endpoint, "minio.$AN.svc:9000", --s3-plain-http, --bucket, kubecost-audit, --create-bucket,
               --tls-cert, /tls/tls.crt, --tls-key, /tls/tls.key, --token-file, /tok/token, --mode, COMPLIANCE, --retain, 24h]
        env:
        - {name: S3_ACCESS_KEY, valueFrom: {secretKeyRef: {name: s3, key: access}}}
        - {name: S3_SECRET_KEY, valueFrom: {secretKeyRef: {name: s3, key: secret}}}
        ports: [{containerPort: 8443}]
        volumeMounts: [{name: tls, mountPath: /tls, readOnly: true}, {name: tok, mountPath: /tok, readOnly: true}]
        resources: {requests: {cpu: 50m, memory: 64Mi}}
      volumes:
      - {name: tls, secret: {secretName: collector-tls}}
      - {name: tok, secret: {secretName: collector-token}}
---
apiVersion: v1
kind: Service
metadata: {name: audit-collector, namespace: $AN}
spec: {selector: {app: audit-collector}, ports: [{port: 8443, targetPort: 8443}]}
EOF
$K -n $AN rollout status deploy/minio --timeout=3m >/dev/null
for _ in $(seq 1 30); do $K -n $AN rollout status deploy/audit-collector --timeout=10s >/dev/null 2>&1 && break; $K -n $AN rollout restart deploy/audit-collector >/dev/null 2>&1; sleep 5; done
check "the collector serves (bucket created with Object Lock, COMPLIANCE)" "$K -n $AN logs deploy/audit-collector 2>&1 | grep -q 'serving on :8443, bucket kubecost-audit, COMPLIANCE'"
python "$HERE/hack/lab/make-copies.py" worm1 worm2 | $K apply -f - >/dev/null
POLICY=$'allowNamespaces: [lab]\nmaxChangeFraction: 0.6\nmaxChanges: 9\nper: 1h\nminConfidence: Medium\n'
printf '%s' "$POLICY" > "$LAB/policy.yaml"
$H upgrade --install "$REL" "$HERE/deploy/helm/kubecost-auto-hpa" -n "$NS" --create-namespace \
  --set operator.image.repository=kubecost-auto-hpa-operator --set operator.image.tag=lab --set operator.image.pullPolicy=Never \
  --set engine.image.repository=kubecost-auto-hpa-engine --set engine.image.tag=lab --set engine.image.pullPolicy=Never \
  --set operator.replicas=1 --set engine.replicas=1 --set operator.leaderElect=false \
  --set operator.podDisruptionBudget.enabled=false --set engine.podDisruptionBudget.enabled=false \
  --set prometheus.url=http://prom-prometheus-server.monitoring:80 --set kubecost.url= \
  --set operator.recommendationApplier.enabled=true --set "operator.recommendationApplier.namespaces={lab}" \
  --set operator.recommendationApplier.maxObserve=90s --set-string "operator.recommendationApplier.policy=$POLICY" \
  --set operator.recommendationApplier.auditURL="https://audit-collector.$AN.svc:8443/events" \
  --set operator.recommendationApplier.auditTokenSecret.name=audit-token --set operator.recommendationApplier.auditCASecret.name=audit-ca \
  --set operator.observeOnly=false --wait --timeout 5m > "$LAB/helm.out" 2>&1 || { cat "$LAB/helm.out"; exit 2; }
OP="deploy/$REL-kubecost-auto-hpa-operator"
check "the operator runs with --audit-ca-file" "$K -n $NS get $OP -o jsonpath='{.spec.template.spec.containers[0].args}' | grep -q 'audit-ca-file=/var/run/kubecost-audit-ca/ca.crt'"
$K apply -f "$HERE/deploy/rbac/rightsize.yaml" >/dev/null
$K -n lab create sa rs-appr --dry-run=client -o yaml | $K apply -f - >/dev/null
$K create clusterrolebinding rs-appr-read --clusterrole=kubecost-rightsize-read --serviceaccount=lab:rs-appr --dry-run=client -o yaml | $K apply -f - >/dev/null
$K -n lab create rolebinding rs-appr --clusterrole=kubecost-rightsize-approve --serviceaccount=lab:rs-appr --dry-run=client -o yaml | $K apply -f - >/dev/null

echo "== 1. the collector's TLS and token are enforced (through a port-forward)"
pf $AN audit-collector 18443:8443
# python's ssl (OpenSSL), not Git Bash's curl (Schannel, which reads the Windows store)
tlsprobe() { python - "$@" <<'PY'
import ssl, sys, urllib.request, urllib.error
ca, tok = sys.argv[1], sys.argv[2]
ctx = ssl.create_default_context(cafile=None if ca == "-" else ca)
req = urllib.request.Request("https://localhost:18443/events", data=b'{"type":"probe"}', headers={"Authorization": "Bearer " + tok})
try:
    print(urllib.request.urlopen(req, context=ctx, timeout=5).status)
except urllib.error.HTTPError as e:
    print(e.code)
except Exception as e:
    print("tls-refused" if "CERTIFICATE_VERIFY_FAILED" in str(e) else "error: %s" % e)
PY
}
NOCA="$(tlsprobe - x)"; echo "without the CA: $NOCA"
check "a client without the private CA is refused by TLS verification" "[ \"$NOCA\" = tls-refused ]"
CODE="$(tlsprobe "$LAB/ca.crt" wrong)"
check "a wrong token gets 401 (got $CODE)" "[ \"$CODE\" = 401 ]"

for w in worm1 worm2; do $K -n lab rollout status deploy/$w --timeout=3m >/dev/null; done
echo "waiting for history (14 min window, 8 min minimum)"; sleep 540

echo "== 2. the OPERATOR ships its applier events over https (private CA, token) into the locked bucket"
B1="$(req worm1)"
plan worm1 "$LAB/rec-worm1.json" --publish || bad "no usable recommendation for worm1"
W1="$(wname "$LAB/rec-worm1.json")"; sleep 10
"$RS" approve --cr --recommendation "$LAB/rec-worm1.json" --context "$CTX" --as system:serviceaccount:lab:rs-appr > "$LAB/approve-worm1.out" 2>&1
waitphase "$W1" Verified 60
check "worm1 Verified ($B1 -> $(req worm1))" "[ \"\$(phase $W1)\" = Verified ]"
sleep 10
check "the operator logged no audit-shipping error" "! $K -n $NS logs $OP 2>&1 | grep -qi 'audit shipping\\|could not be delivered'"

echo "== 3. the CLI ships a CHAINED trail over https to the same collector"
plan worm2 "$LAB/rec-worm2.json" || bad "no usable recommendation for worm2"
pf $AN audit-collector 18443:8443
AU=(--audit-file "$LAB/audit.jsonl" --audit-url "https://localhost:18443/events" --audit-token-file "$LAB/token" --audit-ca-file "$LAB/ca.crt")
"$RS" approve --recommendation "$LAB/rec-worm2.json" --context "$CTX" "${AU[@]}" > "$LAB/approve-worm2.out" 2>&1
"$RS" apply --recommendation "$LAB/rec-worm2.json" --policy "$LAB/policy.yaml" --context "$CTX" --execute --observe-for 90s --poll 15s \
  --rollout-timeout 3m "${AU[@]}" > "$LAB/apply-worm2.out" 2> "$LAB/apply-worm2.err"
echo "apply exit $?"
check "the CLI reported no undelivered events" "! grep -q 'could not be delivered' \"$LAB/apply-worm2.err\" \"$LAB/approve-worm2.out\""

echo "== 4. read the bucket back: content, chain, and the lock"
pf $AN minio 19000:9000
export S3_ACCESS_KEY="$S3K" S3_SECRET_KEY="$S3S"
"$AC" dump --s3-endpoint localhost:19000 --s3-plain-http --bucket kubecost-audit > "$LAB/bucket.jsonl" 2> "$LAB/dump.err"
echo "objects in the bucket: $(wc -l < "$LAB/bucket.jsonl")"
R1=$(python -c "import json,sys; print(json.load(open(sys.argv[1]))['ID'])" "$LAB/rec-worm1.json")
R2=$(python -c "import json,sys; print(json.load(open(sys.argv[1]))['ID'])" "$LAB/rec-worm2.json")
grep "\"recommendationId\":\"$R1\"" "$LAB/bucket.jsonl" > "$LAB/bucket-worm1.jsonl"
grep "\"recommendationId\":\"$R2\"" "$LAB/bucket.jsonl" > "$LAB/bucket-worm2.jsonl"
check "the operator's applied and verified events for worm1 are in the bucket" "grep -q '\"type\":\"applied\"' \"$LAB/bucket-worm1.jsonl\" && grep -q '\"type\":\"verified\"' \"$LAB/bucket-worm1.jsonl\""
check "the CLI's events in the bucket are byte-for-byte the local chained file" "cmp -s \"$LAB/audit.jsonl\" \"$LAB/bucket-worm2.jsonl\""
"$RS" audit-verify --audit-file "$LAB/bucket-worm2.jsonl" > "$LAB/verify-bucket.json" 2>&1
check "audit-verify passes on the copy read back from the bucket" "[ \$? -eq 0 ]"
"$AC" probe-delete --s3-endpoint localhost:19000 --s3-plain-http --bucket kubecost-audit > "$LAB/probe-delete.json" 2>&1
check "deleting a stored event version is refused by the store, even with the root credentials (COMPLIANCE lock)" "grep -q '\"deleteRefused\": true' \"$LAB/probe-delete.json\" && grep -q '\"lockMode\": \"COMPLIANCE\"' \"$LAB/probe-delete.json\""

echo "== diagnostics"
cat "$LAB/probe-delete.json"; cat "$LAB/verify-bucket.json"
$K -n lab get wrec -o custom-columns=NAME:.metadata.name,PHASE:.status.phase 2>&1
echo; echo "RESULT: $PASS passed, $FAILN failed"
