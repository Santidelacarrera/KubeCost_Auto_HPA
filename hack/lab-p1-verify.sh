#!/usr/bin/env bash
# REAL cluster checks of two ninth-pass paths that had only unit tests (minikube lab, hack/lab-up.sh, Prometheus on :9090):
#   A. the OPERATOR's applier with a policy that requires signed approvals: an unsigned status.approval is Denied and nothing is
#      written; a signed one (rightsize approve --cr --sign-key) is applied and Verified.
#   B. --audit-url: the CLI ships its audit events to a real HTTP collector (hack/lab/audit-collector.py, bearer token, first
#      request refused with 503 to force a retry); the collector's copy must equal the local chained file and verify.
# Do not edit this file while it runs (bash reads scripts incrementally): copy it first for long runs.
set -u
CTX="${CTX:-kubecost-lab}"; PROM="${PROM:-http://localhost:9090}"
HERE="$(cd "$(dirname "$0")/.." && pwd)"; LAB="$HERE/.lab/p1-verify"; rm -rf "$LAB"; mkdir -p "$LAB"
K="kubectl --context $CTX"; H="helm --kube-context $CTX"; REL=applier; NS=kubecost-auto-hpa-system
[ "$CTX" = "kubecost-lab" ] || [ "${ALLOW_CTX:-}" = "1" ] || { echo "refusing context '$CTX'"; exit 2; }
curl -fs "$PROM/-/ready" >/dev/null || { echo "Prometheus not reachable"; exit 2; }
PASS=0; FAILN=0
ok()  { echo "PASS  $*"; PASS=$((PASS+1)); }
bad() { echo "FAIL  $*"; FAILN=$((FAILN+1)); }
check() { if eval "$2"; then ok "$1"; else bad "$1"; fi; }
(cd "$HERE/operator" && go build -o "$LAB/rightsize.exe" ./cmd/rightsize) || exit 2
RS="$LAB/rightsize.exe"
req() { $K -n lab get deploy "$1" -o jsonpath='{.spec.template.spec.containers[0].resources.requests.cpu}/{.spec.template.spec.containers[0].resources.requests.memory}'; }
phase() { $K -n lab get wrec "$1" -o jsonpath='{.status.phase}' 2>/dev/null; }
waitphase() { for _ in $(seq 1 "$3"); do [ "$(phase "$1")" = "$2" ] && return 0; sleep 5; done; return 1; }
# plan WORKLOAD OUT [--publish]: retry until a usable (not abstained, Medium or better) recommendation exists
plan() { for _ in $(seq 1 45); do
    "$RS" plan --context "$CTX" --prometheus-url "$PROM" --namespace lab --workload "$1" --container app --window 14m --step 15s \
      --min-window 8m --min-samples 40 ${3:-} > "$2" 2>"$2.err" &&
    [ "$(python -c "import json,sys; r=json.load(open(sys.argv[1])); print(not r['Abstained'] and r['Confidence'] in ('Medium','High'))" "$2")" = True ] && return 0
    sleep 20; done; return 1; }
wname() { python -c "import json,sys; r=json.load(open(sys.argv[1])); print(r['Workload'].lower() + '-' + r['ID'].lower())" "$1"; }

echo "== 0. approver key, workloads, operator image, chart (applier ON for lab, observe-only OFF, signed approvals REQUIRED)"
"$RS" keygen --out "$LAB/approver" > "$LAB/keygen.json" || exit 2
KID="$(python -c "import json,sys; print(json.load(open(sys.argv[1]))['keyID'])" "$LAB/keygen.json")"
# the policy takes the raw 32-byte key as base64 (the last 32 bytes of the PEM's SubjectPublicKeyInfo)
PUB="$(python -c "import base64,sys; t=open(sys.argv[1]).read(); b=''.join(l for l in t.splitlines() if '-----' not in l); print(base64.b64encode(base64.b64decode(b)[-32:]).decode())" "$LAB/approver.pub")"
$K create ns lab >/dev/null 2>&1
python "$HERE/hack/lab/make-copies.py" sig1 sig2 aud1 | $K apply -f - >/dev/null
docker build -q -t kubecost-auto-hpa-operator:lab --build-arg VERSION=lab "$HERE/operator" >/dev/null || exit 2
docker build -q -t kubecost-auto-hpa-engine:lab "$HERE/engine" >/dev/null || exit 2
minikube -p kubecost-lab image load kubecost-auto-hpa-operator:lab kubecost-auto-hpa-engine:lab || exit 2
POLICY=$'allowNamespaces: [lab]\nmaxChangeFraction: 0.6\nmaxChanges: 9\nper: 1h\nminConfidence: Medium\nrequireSignedApproval: true\napproverKeys:\n  '"$KID: $PUB"$'\n'
printf '%s' "$POLICY" > "$LAB/policy.yaml"
$H upgrade --install "$REL" "$HERE/deploy/helm/kubecost-auto-hpa" -n "$NS" --create-namespace \
  --set operator.image.repository=kubecost-auto-hpa-operator --set operator.image.tag=lab --set operator.image.pullPolicy=Never \
  --set engine.image.repository=kubecost-auto-hpa-engine --set engine.image.tag=lab --set engine.image.pullPolicy=Never \
  --set operator.replicas=1 --set engine.replicas=1 --set operator.leaderElect=false \
  --set operator.podDisruptionBudget.enabled=false --set engine.podDisruptionBudget.enabled=false \
  --set prometheus.url=http://prom-prometheus-server.monitoring:80 --set kubecost.url= \
  --set operator.recommendationApplier.enabled=true --set "operator.recommendationApplier.namespaces={lab}" \
  --set operator.recommendationApplier.maxObserve=90s --set-string "operator.recommendationApplier.policy=$POLICY" \
  --set operator.observeOnly=false --wait --timeout 5m > "$LAB/helm.out" 2>&1 || { cat "$LAB/helm.out"; exit 2; }
OP="deploy/$REL-kubecost-auto-hpa-operator"
check "the operator runs the applier" "$K -n $NS logs $OP --tail=80 2>&1 | grep -q 'recommendation applier enabled'"
$K apply -f "$HERE/deploy/rbac/rightsize.yaml" >/dev/null
$K -n lab create sa rs-appr --dry-run=client -o yaml | $K apply -f - >/dev/null
$K create clusterrolebinding rs-appr-read --clusterrole=kubecost-rightsize-read --serviceaccount=lab:rs-appr --dry-run=client -o yaml | $K apply -f - >/dev/null
$K -n lab create rolebinding rs-appr --clusterrole=kubecost-rightsize-approve --serviceaccount=lab:rs-appr --dry-run=client -o yaml | $K apply -f - >/dev/null
for w in sig1 sig2 aud1; do $K -n lab rollout status deploy/$w --timeout=3m >/dev/null; done
echo "waiting for history (14 min window, 8 min minimum)"; sleep 540

echo "== A1. an UNSIGNED approval of an object is refused by the operator's policy; the workload is untouched"
B1="$(req sig1)"
plan sig1 "$LAB/rec-sig1.json" --publish || bad "no usable recommendation for sig1"
W1="$(wname "$LAB/rec-sig1.json")"; sleep 10
"$RS" approve --cr --recommendation "$LAB/rec-sig1.json" --context "$CTX" --as system:serviceaccount:lab:rs-appr > "$LAB/approve-sig1.out" 2>&1
waitphase "$W1" Denied 24
check "phase Denied" "[ \"\$(phase $W1)\" = Denied ]"
check "the reason names the missing signature" "$K -n lab get wrec $W1 -o jsonpath='{.status.reasons}' | grep -q 'signed approval required'"
sleep 20
check "sig1 untouched" "[ \"\$(req sig1)\" = \"$B1\" ]"

echo "== A2. a SIGNED approval (approve --cr --sign-key) is applied by the operator and Verified"
B2="$(req sig2)"
plan sig2 "$LAB/rec-sig2.json" --publish || bad "no usable recommendation for sig2"
W2="$(wname "$LAB/rec-sig2.json")"; sleep 10
"$RS" approve --cr --recommendation "$LAB/rec-sig2.json" --context "$CTX" --as system:serviceaccount:lab:rs-appr --sign-key "$LAB/approver.key" > "$LAB/approve-sig2.out" 2>&1
check "the signature is in status.approval" "$K -n lab get wrec $W2 -o jsonpath='{.status.approval.signature}' | grep -q '^$KID:'"
waitphase "$W2" Verified 60
check "phase Verified" "[ \"\$(phase $W2)\" = Verified ]"
A2="$(req sig2)"; echo "sig2 requests: $B2 -> $A2"
check "sig2 really changed" "[ \"$A2\" != \"$B2\" ]"

echo "== B. --audit-url: events shipped to a real collector equal the local chained file"
TOKEN="lab-$RANDOM$RANDOM"; printf '%s' "$TOKEN" > "$LAB/token"; PORT=18555
python "$HERE/hack/lab/audit-collector.py" $PORT "$TOKEN" "$LAB/collected.jsonl" & CPID=$!
sleep 2
plan aud1 "$LAB/rec-aud1.json" || bad "no usable recommendation for aud1"
AU=(--audit-file "$LAB/audit.jsonl" --audit-url "http://127.0.0.1:$PORT/events" --audit-token-file "$LAB/token")
"$RS" approve --recommendation "$LAB/rec-aud1.json" --context "$CTX" --sign-key "$LAB/approver.key" "${AU[@]}" > "$LAB/approve-aud1.out" 2>&1
"$RS" apply --recommendation "$LAB/rec-aud1.json" --policy "$LAB/policy.yaml" --context "$CTX" --execute --observe-for 90s --poll 15s \
  --rollout-timeout 3m "${AU[@]}" > "$LAB/apply-aud1.out" 2> "$LAB/apply-aud1.err"
echo "apply exit $?"
sleep 2; kill $CPID 2>/dev/null
N1=$(wc -l < "$LAB/audit.jsonl"); N2=$(wc -l < "$LAB/collected.jsonl" 2>/dev/null || echo 0); echo "local $N1 events, collected $N2"
check "the collector received every event (the first POST was refused with 503 and retried)" "[ \"$N1\" -gt 0 ] && [ \"$N1\" = \"$N2\" ]"
check "the collector's copy is byte-for-byte the local chained file" "cmp -s \"$LAB/audit.jsonl\" \"$LAB/collected.jsonl\""
"$RS" audit-verify --audit-file "$LAB/collected.jsonl" > "$LAB/verify-collected.json" 2>&1
check "audit-verify passes on the collector's copy" "[ \$? -eq 0 ]"
check "no undelivered events reported" "! grep -q 'could not be delivered' \"$LAB/apply-aud1.err\" \"$LAB/approve-aud1.out\""

echo "== diagnostics"
$K -n lab get wrec -o custom-columns=NAME:.metadata.name,PHASE:.status.phase,MSG:.status.message 2>&1
cat "$LAB/verify-collected.json"
echo; echo "RESULT: $PASS passed, $FAILN failed"
